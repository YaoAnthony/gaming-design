export const GLYPH_W = 3, GLYPH_H = 5, GLYPH_GAP = 1, LINE_GAP = 1;

/** 一串字（可含 '\n'）在锚点 (ox, oy) 展开后占哪些格子（相对房间的格坐标） */
export function layoutText(text: string, ox: number, oy: number): { x: number; y: number }[] {
  const out: { x: number; y: number }[] = [];
  text.toUpperCase().split('\n').forEach((line, li) => {
    const ly = oy + li * (GLYPH_H + LINE_GAP);
    [...line].forEach((ch, ci) => {
      const g = GLYPHS[ch] ?? GLYPHS[' '];
      const lx = ox + ci * (GLYPH_W + GLYPH_GAP);
      g.forEach((row, ry) => [...row].forEach((c, rx) => { if (c === '#') out.push({ x: lx + rx, y: ly + ry }); }));
    });
  });
  return out;
}

/** 一串字的宽高（格） */
export function textSize(text: string): { w: number; h: number } {
  const lines = text.toUpperCase().split('\n');
  const w = Math.max(0, ...lines.map(l => l.length * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP));
  return { w, h: lines.length * (GLYPH_H + LINE_GAP) - LINE_GAP };
}

